// Online recommender hook: builds a user profile from the local view history,
// then ranks the catalogue using the trained ML artifacts (embeddings,
// neighbours, popularity) from src/recommender/models/. Artifacts are produced
// by ml/train.py — retrain by running `python ml/train.py` from the project root.
import { useCallback, useMemo, useState } from 'react';
import {
  buildUserProfile,
  cosine,
  l2Norm,
  tokenize,
  searchRelevance,
  REC_WEIGHTS,
} from './model';
import {
  loadViewHistory,
  recordPlaceView,
  clearViewHistory,
  loadSearchHistory,
  recordSearchTerm,
} from './storage';

// CRA supports JSON imports; generated by ml/train.py (merged core + supplemental catalogue).
import embeddingsArtifact from './models/embeddings.json';
import neighborsArtifact from './models/neighbors.json';
import popularityArtifact from './models/popularity.json';

function flatItems(districts) {
  return districts
    ? districts.flatMap(d =>
        (d.touristPlaces || []).map(p => ({ ...p, districtName: d.name, coords: d.coordinates }))
      )
    : [];
}

export default function useRecommender(districts) {
  const items = useMemo(() => flatItems(districts), [districts]);

  const artifacts = useMemo(() => {
    const artIndex = new Map(embeddingsArtifact.names.map((n, i) => [n, i]));
    const vectors = items.map(it => {
      const idx = artIndex.get(it.name);
      return idx == null ? null : embeddingsArtifact.vectors[idx];
    });
    const norms = vectors.map(v => (v ? l2Norm(v) : 0));
    const popMap = new Map(popularityArtifact.names.map((n, i) => [n, popularityArtifact.scores[i]]));
    const popularity = items.map(it => popMap.get(it.name) ?? 0.5);
    const edgesByName = new Map(neighborsArtifact.names.map((n, i) => [n, neighborsArtifact.edges[i]]));
    return { artIndex, vectors, norms, popularity, edgesByName };
  }, [items]);

  const [viewHistory, setViewHistory] = useState(loadViewHistory);
  const [searchHistory, setSearchHistory] = useState(loadSearchHistory);

  const viewNames = useMemo(() => new Set(viewHistory.map(v => v.name)), [viewHistory]);

  const profile = useMemo(() => {
    const entries = viewHistory
      .map(h => {
        const idx = artifacts.artIndex.get(h.name);
        return idx == null ? null : { vector: artifacts.vectors[idx], ts: h.ts, name: h.name };
      })
      .filter(Boolean);
    return buildUserProfile(entries);
  }, [viewHistory, artifacts]);

  const lastViewedName = viewHistory[viewHistory.length - 1]?.name || null;

  const recordView = useCallback(
    (place, districtName) => {
      const entry = {
        name: place.name,
        district: districtName,
        type: place.type,
        ts: Date.now(),
      };
      setViewHistory(recordPlaceView(entry));
    },
    []
  );

  const recordSearch = useCallback(
    query => {
      setSearchHistory(recordSearchTerm(query));
    },
    []
  );

  const clearHistory = useCallback(() => {
    setViewHistory(clearViewHistory());
    setSearchHistory([]);
  }, []);

  /**
   * "Up next" / home strip. Excludes already-viewed places. Falls back to
   * popularity-only (Trending) when there is no viewing history yet.
   */
  const recommend = useCallback(
    (limit = 10) => {
      const candidates = [];
      for (let i = 0; i < items.length; i++) {
        const place = items[i];
        if (viewNames.has(place.name)) continue;
        if (!artifacts.vectors[i]) continue;
        const sim = profile.norm ? cosine(profile.vector, artifacts.vectors[i], profile.norm, artifacts.norms[i]) : 0;
        const pop = artifacts.popularity[i];
        const fresh = 0;
        const score =
          (Math.max(0, sim) + 1) * 0.5 * REC_WEIGHTS.similarity +
          pop * REC_WEIGHTS.popularity +
          fresh * REC_WEIGHTS.freshness;
        const reasons = [];
        if (profile.count > 0 && sim > 0.35) reasons.push('similar');
        if (pop >= 0.9) reasons.push('trend');
        if (profile.count === 0) reasons.push('trend');
        candidates.push({ item: place, score: Math.round(score * 1000) / 1000, sim, popularity: pop, reasons });
      }
      candidates.sort((a, b) => b.score - a.score);
      return candidates.slice(0, limit);
    },
    [items, artifacts, profile, viewNames]
  );

  /**
   * "More places like this" — item-to-item similarity from the precomputed
   * neighbour graph (falls back to dense cosine over embeddings).
   */
  const similarTo = useCallback(
    (place, limit = 8) => {
      const artIdx = artifacts.artIndex.get(place.name);
      const out = [];
      if (artIdx != null && artifacts.edgesByName.has(place.name)) {
        for (const [neighborArtIdx, similarity] of artifacts.edgesByName.get(place.name)) {
          const item = items[neighborArtIdx];
          if (!item || item.name === place.name) continue;
          if (item.districtName === place.districtName) continue; // keep suggestions fresh
          out.push({ item, similarity });
          if (out.length >= limit) break;
        }
      }
      if (out.length === 0 && artIdx != null) {
        for (let i = 0; i < items.length; i++) {
          if (i === artIdx || items[i].districtName === place.districtName) continue;
          out.push({
            item: items[i],
            similarity: cosine(artifacts.vectors[artIdx], artifacts.vectors[i], artifacts.norms[artIdx], artifacts.norms[i]),
          });
        }
        out.sort((a, b) => b.similarity - a.similarity);
      }
      return out.slice(0, limit);
    },
    [items, artifacts]
  );

  /**
   * YouTube-style personalised search: keeps the lexical matches but re-ranks
   * places by blending query relevance with the user profile. District matches
   * keep their order and lead the list.
   */
  const rankSearch = useCallback(
    (rawMatches, query) => {
      const q = String(query || '').trim().toLowerCase();
      if (!q) return [];
      const tqs = tokenize(q);
      const districtSort = rawMatches
        .filter(m => m.type === 'district')
        .sort((a, b) => {
          const ea = d => (d.name.toLowerCase() === q ? 3 : d.name.toLowerCase().includes(q) ? 2 : 1);
          return ea(b.data) - ea(a.data);
        });
      const placeSort = rawMatches
        .filter(m => m.type === 'place')
        .map(m => {
          const idx = artifacts.artIndex.get(m.data.name);
          const relevance = idx == null ? 1 : searchRelevance(tqs, { ...m.data, districtName: m.district?.name });
          const personalization =
            idx != null && profile.norm
              ? Math.max(0, cosine(profile.vector, artifacts.vectors[idx], profile.norm, artifacts.norms[idx]))
              : 0;
          const score = relevance * (1 + personalization) * (1 + artifacts.popularity[idx ?? 0] * 0.2);
          return {
            ...m,
            relevance: Math.round(relevance * 1000) / 1000,
            personalization: Math.round(personalization * 1000) / 1000,
            score: Math.round(score * 1000) / 1000,
            becauseOf: personalization > 0.3 && profile.count > 0 ? lastViewedName : null,
          };
        })
        .sort((a, b) => b.score - a.score);
      return [...districtSort, ...placeSort];
    },
    [artifacts, profile, lastViewedName]
  );

  return {
    items,
    viewHistory,
    viewNames,
    searchHistory,
    profile,
    profileCount: profile.count,
    lastViewedName,
    recommend,
    similarTo,
    rankSearch,
    recordView,
    recordSearch,
    clearHistory,
    weights: REC_WEIGHTS,
  };
}