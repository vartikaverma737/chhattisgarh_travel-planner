const translations = { en, hi, cg };

export function translate(lang, key, params) {
  const dict = translations[lang] || en;
  let text = dict[key] ?? en[key] ?? key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replaceAll(`{${k}}`, String(v));
    });
  }
  return text;
}

const LanguageContext = createContext({ lang: 'en', setLang: () => {}, t: (k, p) => translate('en', k, p) });

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => {
    try { return localStorage.getItem('cg-language') || 'en'; } catch { return 'en'; }
  });

  useEffect(() => {
    try { localStorage.setItem('cg-language', lang); } catch {}
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (key, params) => translate(lang, key, params);

  return <LanguageContext.Provider value={{ lang, setLang, t }}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext);
}